/**
 * Render the native front-end login form.
 *
 * Usage: [ame_login_form title="Masuk ke Akun" redirect="/"]
 *
 * @param array|string $atts Shortcode attributes.
 * @return string
 */
function ame_login_form_shortcode( $atts ) {
	if ( ! get_theme_mod( 'ame_frontend_login_enabled', true ) ) {
		return '';
	}

	$atts = shortcode_atts(
		array(
			'title'    => __( 'Masuk ke Akun', 'andalan-mutu-energi' ),
			'redirect' => '',
		),
		$atts,
		'ame_login_form'
	);
	$return = is_singular() ? get_permalink( get_queried_object_id() ) : home_url( '/' );
	$return = $return ? $return : home_url( '/' );
	$requested_redirect = isset( $_GET['redirect_to'] ) && is_string( $_GET['redirect_to'] ) ? esc_url_raw( wp_unslash( $_GET['redirect_to'] ) ) : '';
	$requested_redirect = $requested_redirect ? wp_validate_redirect( $requested_redirect, $return ) : '';
	$redirect = $atts['redirect'] ? esc_url_raw( $atts['redirect'] ) : ( $requested_redirect ? $requested_redirect : $return );
	$redirect = wp_validate_redirect( $redirect, $return );
	$title    = sanitize_text_field( $atts['title'] );
	$form_id  = wp_unique_id( 'ame-login-' );

	wp_enqueue_style( 'andalan-mutu-energi-login' );
	$challenge_id = isset( $_GET['ame_2fa'] ) && is_string( $_GET['ame_2fa'] ) ? sanitize_text_field( wp_unslash( $_GET['ame_2fa'] ) ) : '';
	if ( $challenge_id ) {
		return ame_2fa_form_html( $challenge_id );
	}
	ob_start();
	?>
	<div class="ame-login-card">
		<?php if ( $title ) : ?><h2 class="ame-login-title"><?php echo esc_html( $title ); ?></h2><?php endif; ?>
		<?php if ( is_user_logged_in() ) : ?>
			<?php $current_user = wp_get_current_user(); ?>
			<p class="ame-login-status"><?php echo esc_html( sprintf( __( 'Anda sudah masuk sebagai %s.', 'andalan-mutu-energi' ), $current_user->display_name ) ); ?></p>
			<div class="ame-login-actions">
				<?php if ( current_user_can( 'edit_posts' ) ) : ?><a class="ame-login-button" href="<?php echo esc_url( admin_url() ); ?>"><?php esc_html_e( 'Buka Dashboard', 'andalan-mutu-energi' ); ?></a><?php endif; ?>
				<a class="ame-login-secondary" href="<?php echo esc_url( wp_logout_url( add_query_arg( 'ame_login_message', 'loggedout', $return ) ) ); ?>"><?php esc_html_e( 'Keluar', 'andalan-mutu-energi' ); ?></a>
			</div>
		<?php else : ?>
			<?php if ( isset( $_GET['ame_login_message'] ) && 'loggedout' === $_GET['ame_login_message'] ) : ?>
				<div class="ame-login-success" role="status"><?php esc_html_e( 'Anda telah keluar dengan aman.', 'andalan-mutu-energi' ); ?></div>
			<?php endif; ?>
			<?php
			$error = isset( $_GET['ame_login_error'] ) && is_string( $_GET['ame_login_error'] ) ? sanitize_key( wp_unslash( $_GET['ame_login_error'] ) ) : '';
			$message = $error ? ame_login_error_message( $error ) : '';
			?>
			<?php if ( $message ) : ?><div class="ame-login-error" role="alert"><?php echo esc_html( $message ); ?></div><?php endif; ?>
			<form class="ame-login-form" method="post" action="<?php echo esc_url( admin_url( 'admin-post.php' ) ); ?>">
				<input type="hidden" name="action" value="ame_frontend_login">
				<input type="hidden" name="ame_login_return" value="<?php echo esc_attr( $return ); ?>">
				<input type="hidden" name="redirect_to" value="<?php echo esc_attr( $redirect ); ?>">
				<div class="ame-login-field">
					<label for="<?php echo esc_attr( $form_id . 'user' ); ?>"><?php esc_html_e( 'Username atau email', 'andalan-mutu-energi' ); ?></label>
					<input id="<?php echo esc_attr( $form_id . 'user' ); ?>" type="text" name="log" autocomplete="username" required>
				</div>
				<div class="ame-login-field">
					<label for="<?php echo esc_attr( $form_id . 'password' ); ?>"><?php esc_html_e( 'Password', 'andalan-mutu-energi' ); ?></label>
					<input id="<?php echo esc_attr( $form_id . 'password' ); ?>" type="password" name="pwd" autocomplete="current-password" required>
				</div>
				<div class="ame-login-remember"><label for="<?php echo esc_attr( $form_id . 'remember' ); ?>"><input id="<?php echo esc_attr( $form_id . 'remember' ); ?>" type="checkbox" name="rememberme" value="1"> <?php esc_html_e( 'Ingat saya', 'andalan-mutu-energi' ); ?></label></div>
				<?php echo ame_login_captcha_fields(); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Internally escaped form markup. ?>
				<button class="ame-login-button" type="submit"><?php esc_html_e( 'Masuk', 'andalan-mutu-energi' ); ?></button>
			</form>
			<p class="ame-login-help"><a href="<?php echo esc_url( wp_lostpassword_url( $return ) ); ?>"><?php esc_html_e( 'Lupa password?', 'andalan-mutu-energi' ); ?></a></p>
		<?php endif; ?>
	</div>
	<?php
	return ob_get_clean();
}
add_shortcode( 'ame_login_form', 'ame_login_form_shortcode' );

/**
 * Redirect back to the form with a public-safe error code.
 *
 * @param string $code   Error code.
 * @param string $return Validated local form URL.
 * @return void
 */
function ame_login_redirect_error( $code, $return ) {
	$return = remove_query_arg( 'ame_login_error', $return );
	$return = add_query_arg( 'ame_login_error', sanitize_key( $code ), $return );
	wp_safe_redirect( $return );
	exit;
}

/**
 * Process the front-end login form and return to its originating page on error.
 *
 * @return void
 */
function ame_login_handle_frontend() {
	$fallback = home_url( '/' );
	$return   = ame_login_post_value( 'ame_login_return' );
	$return   = $return ? wp_validate_redirect( esc_url_raw( $return ), $fallback ) : $fallback;
	$redirect = ame_login_post_value( 'redirect_to' );
	$redirect = $redirect ? wp_validate_redirect( esc_url_raw( $redirect ), $return ) : $return;

	if ( ! get_theme_mod( 'ame_frontend_login_enabled', true ) ) {
		ame_login_redirect_error( 'disabled', $return );
	}
	if ( is_user_logged_in() ) {
		wp_safe_redirect( $redirect );
		exit;
	}
	if ( get_theme_mod( 'ame_login_captcha_enabled', true ) && ! ame_login_captcha_validate_request() ) {
		ame_login_redirect_error( 'captcha', $return );
	}

	$username = trim( sanitize_text_field( ame_login_post_value( 'log' ) ) );
	$password = ame_login_post_value( 'pwd' );
	if ( '' === $username || '' === $password ) {
		ame_login_redirect_error( 'credentials', $return );
	}

	$user = wp_signon(
		array(
			'user_login'    => $username,
			'user_password' => $password,
			'remember'      => (bool) ame_login_post_value( 'rememberme' ),
		),
		is_ssl()
	);
	if ( is_wp_error( $user ) ) {
		if ( 'ame_2fa_required' === $user->get_error_code() ) {
			ame_2fa_redirect_to_verification( $user->get_error_data() );
		}
		$code = 'ame_temporarily_blocked' === $user->get_error_code() ? 'blocked' : 'credentials';
		if ( 'ame_captcha_failed' === $user->get_error_code() ) {
			$code = 'captcha';
		} elseif ( 'ame_2fa_email_failed' === $user->get_error_code() ) {
			$code = '2fa_email';
		} elseif ( 'ame_2fa_email_limit' === $user->get_error_code() ) {
			$code = '2fa_rate';
		}
		ame_login_redirect_error( $code, $return );
	}

	wp_safe_redirect( $redirect );
	exit;
}
add_action( 'admin_post_ame_frontend_login', 'ame_login_handle_frontend' );
add_action( 'admin_post_nopriv_ame_frontend_login', 'ame_login_handle_frontend' );
