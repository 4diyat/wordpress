/**
 * Native front-end login and privacy-friendly arithmetic CAPTCHA.
 *
 * CAPTCHA challenges are signed with a WordPress salt and expire after two
 * hours. They require no third-party request, CAPTCHA cookie, or stored answer.
 * WordPress still uses its normal authentication cookies after a successful
 * login. This lightweight challenge is not a replacement for enterprise bot
 * detection or the firewall's rate limits.
 *
 * @package Andalan_Mutu_Energi
 */

