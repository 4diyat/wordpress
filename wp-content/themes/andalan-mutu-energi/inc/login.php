/**
 * Return a public-safe login error message.
 *
 * @param string $code Internal error code.
 * @return string
 */
function ame_login_error_message( $code ) {
	$messages = array(
		'credentials' => __( 'Login tidak berhasil. Periksa kembali username/email dan password Anda.', 'andalan-mutu-energi' ),
		'captcha'     => __( 'Jawaban CAPTCHA tidak valid atau sudah kedaluwarsa. Silakan coba lagi.', 'andalan-mutu-energi' ),
		'blocked'     => __( 'Akses login dibatasi sementara karena terlalu banyak percobaan. Silakan coba lagi nanti.', 'andalan-mutu-energi' ),
		'disabled'    => __( 'Login front-end sedang nonaktif.', 'andalan-mutu-energi' ),
		'2fa_email'   => __( 'Kode verifikasi tidak dapat dikirim. Periksa konfigurasi email/SMTP atau hubungi administrator.', 'andalan-mutu-energi' ),
