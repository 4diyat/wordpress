define( 'AME_LOGIN_VERSION', '1.0' );

/**
 * Create or locate the front-end login page without replacing existing pages.
 *
 * @return int Login page ID, or zero on failure.
 */
function ame_login_install() {
	$page_id = (int) get_option( 'ame_login_page_id' );
	if ( $page_id && 'page' === get_post_type( $page_id ) && 'trash' !== get_post_status( $page_id ) ) {
		update_option( 'ame_login_features_version', AME_LOGIN_VERSION, false );
		return $page_id;
	}

	$existing = get_posts(
		array(
			'post_type'              => 'page',
			'post_status'            => array( 'publish', 'private', 'draft' ),
			'posts_per_page'         => 1,
			'fields'                 => 'ids',
			's'                      => '[ame_login_form',
			'no_found_rows'          => true,
			'update_post_meta_cache' => false,
			'update_post_term_cache' => false,
		)
	);
	if ( $existing ) {
		$page_id = (int) $existing[0];
	} else {
		$page_id = wp_insert_post(
			array(
				'post_type'      => 'page',
				'post_status'    => 'publish',
				'post_title'     => __( 'Masuk', 'andalan-mutu-energi' ),
				'post_name'      => 'masuk',
				'post_content'   => '[ame_login_form title=""]',
				'comment_status' => 'closed',
				'ping_status'    => 'closed',
			),
			true
		);
	}

	if ( is_wp_error( $page_id ) || ! $page_id ) {
		return 0;
	}
	$page_id = (int) $page_id;
	update_option( 'ame_login_page_id', $page_id, false );
	update_option( 'ame_login_features_version', AME_LOGIN_VERSION, false );
	update_post_meta( $page_id, '_ame_login_page', '1' );
	return $page_id;
}

/**
 * Install the login page after a theme update when an administrator visits.
 *
 * @return void
 */
function ame_login_maybe_install() {
	if ( current_user_can( 'manage_options' ) && AME_LOGIN_VERSION !== get_option( 'ame_login_features_version' ) ) {
		ame_login_install();
	}
}
add_action( 'admin_init', 'ame_login_maybe_install' );

/**
 * Return the custom login page URL, or an empty string when unavailable.
 *
 * This helper never calls wp_login_url(), so it is safe to use inside the
 * login_url filter without recursion.
 *
 * @return string
 */
function ame_login_custom_page_url() {
	if ( ! get_theme_mod( 'ame_frontend_login_enabled', true ) ) {
		return '';
	}
	$page_id = (int) get_option( 'ame_login_page_id' );
	if ( ! $page_id || 'trash' === get_post_status( $page_id ) ) {
		return '';
	}
	$url = get_permalink( $page_id );
	return $url ? $url : '';
}

/**
 * Return the preferred web login URL with a native fallback.
 *
 * @return string
 */
function ame_login_page_url() {
	$url = ame_login_custom_page_url();
	return $url ? $url : wp_login_url();
}

/**
 * Use the custom page for login links generated by WordPress.
 *
 * @param string $login_url    Native login URL.
 * @param string $redirect     Requested post-login destination.
 * @param bool   $force_reauth Whether reauthentication was requested.
 * @return string
 */
function ame_login_filter_login_url( $login_url, $redirect = '', $force_reauth = false ) {
	if ( ! get_theme_mod( 'ame_replace_wp_login', true ) ) {
		return $login_url;
	}
	$custom_url = ame_login_custom_page_url();
	if ( ! $custom_url ) {
		return $login_url;
	}
	if ( $redirect && is_string( $redirect ) ) {
		$custom_url = add_query_arg( 'redirect_to', $redirect, $custom_url );
	}
	if ( $force_reauth ) {
		$custom_url = add_query_arg( 'reauth', '1', $custom_url );
	}
	return $custom_url;
}
add_filter( 'login_url', 'ame_login_filter_login_url', 10, 3 );

/**
 * Redirect direct visits to the native login screen to the custom page.
 *
 * Credential POSTs are left to WordPress for compatibility with integrations;
 * the custom form itself posts to admin-post.php. Logout, registration,
 * lost/reset password, post password, and recovery flows are not intercepted.
 *
 * @return void
 */
function ame_login_replace_wp_login() {
	if ( ! get_theme_mod( 'ame_replace_wp_login', true ) ) {
		return;
	}
	global $pagenow;
	if ( 'wp-login.php' !== $pagenow || isset( $_POST['log'] ) || isset( $_POST['pwd'] ) ) {
		return;
	}
	$action = isset( $_REQUEST['action'] ) && is_string( $_REQUEST['action'] ) ? sanitize_key( wp_unslash( $_REQUEST['action'] ) ) : '';
	if ( $action && 'login' !== $action ) {
		return;
	}

	$custom_url = ame_login_custom_page_url();
	if ( ! $custom_url ) {
		return;
	}
	$redirect = isset( $_REQUEST['redirect_to'] ) && is_string( $_REQUEST['redirect_to'] ) ? esc_url_raw( wp_unslash( $_REQUEST['redirect_to'] ) ) : '';
	if ( $redirect ) {
		$custom_url = add_query_arg( 'redirect_to', $redirect, $custom_url );
	}
	if ( isset( $_GET['reauth'] ) ) {
		$custom_url = add_query_arg( 'reauth', '1', $custom_url );
	}
	if ( isset( $_GET['loggedout'] ) ) {
		$custom_url = add_query_arg( 'ame_login_message', 'loggedout', $custom_url );
	}
	wp_safe_redirect( $custom_url );
	exit;
}
add_action( 'login_init', 'ame_login_replace_wp_login', 1 );

/**
 * Return one scalar POST value without altering its remaining contents.
 *
 * @param string $key Field name.
 * @return string
 */
function ame_login_post_value( $key ) {
	if ( ! isset( $_POST[ $key ] ) || ! is_string( $_POST[ $key ] ) ) {
		return '';
	}
	return (string) wp_unslash( $_POST[ $key ] );
}

/**
 * Generate a signed arithmetic challenge.
 *
 * @return array<string, string>
 */
function ame_login_captcha_challenge() {
	$a  = wp_rand( 1, 10 );
	$b  = wp_rand( 1, 10 );
	$op = wp_rand( 0, 1 ) ? 'plus' : 'minus';
	if ( 'minus' === $op && $b > $a ) {
		$swap = $a;
		$a    = $b;
		$b    = $swap;
	}

	$payload   = implode( '|', array( $a, $op, $b, time(), wp_generate_password( 32, false, false ) ) );
	$signature = hash_hmac( 'sha256', $payload, wp_salt( 'nonce' ) );
	return array(
		'payload'   => $payload,
		'signature' => $signature,
		'question'  => $a . ' ' . ( 'plus' === $op ? '+' : '−' ) . ' ' . $b . ' = ?',
	);
}

/**
 * Validate the current CAPTCHA and honeypot submission.
 *
 * @return bool
 */
function ame_login_captcha_validate_request() {
	if ( '' !== trim( ame_login_post_value( 'ame_login_website' ) ) ) {
		return false;
	}

	$payload   = trim( sanitize_text_field( ame_login_post_value( 'ame_captcha_payload' ) ) );
	$signature = trim( sanitize_text_field( ame_login_post_value( 'ame_captcha_signature' ) ) );
	$answer    = trim( sanitize_text_field( ame_login_post_value( 'ame_captcha_answer' ) ) );
	if ( strlen( $payload ) > 100 || ! preg_match( '/^[a-f0-9]{64}$/', $signature ) ) {
		return false;
	}
	if ( ! preg_match( '/^[0-9]{1,2}\|(?:plus|minus)\|[0-9]{1,2}\|[0-9]{10}\|[A-Za-z0-9]{32}$/', $payload ) ) {
		return false;
	}

	$expected_signature = hash_hmac( 'sha256', $payload, wp_salt( 'nonce' ) );
	if ( ! hash_equals( $expected_signature, $signature ) ) {
		return false;
	}

	$parts = explode( '|', $payload );
	$a     = (int) $parts[0];
	$op    = $parts[1];
	$b     = (int) $parts[2];
	$time  = (int) $parts[3];
	if ( $a < 1 || $a > 20 || $b < 1 || $b > 20 || ( 'minus' === $op && $b > $a ) ) {
		return false;
	}
	if ( $time > time() + 300 || $time < time() - ( 2 * HOUR_IN_SECONDS ) ) {
		return false;
	}
	if ( ! preg_match( '/^[0-9]{1,3}$/', $answer ) ) {
		return false;
	}

	$expected_answer = 'plus' === $op ? $a + $b : $a - $b;
	return (int) $answer === $expected_answer;
}

/**
 * Return CAPTCHA and honeypot fields for either login form.
 *
 * @return string
 */
function ame_login_captcha_fields() {
	if ( ! get_theme_mod( 'ame_login_captcha_enabled', true ) ) {
		return '';
	}

	$challenge = ame_login_captcha_challenge();
	$field_id  = 'ame-captcha-' . substr( $challenge['signature'], 0, 8 );
	ob_start();
	?>
	<div class="ame-captcha-field">
		<input type="hidden" name="ame_captcha_payload" value="<?php echo esc_attr( $challenge['payload'] ); ?>">
		<input type="hidden" name="ame_captcha_signature" value="<?php echo esc_attr( $challenge['signature'] ); ?>">
		<label for="<?php echo esc_attr( $field_id ); ?>"><?php esc_html_e( 'Verifikasi CAPTCHA:', 'andalan-mutu-energi' ); ?> <strong><?php echo esc_html( $challenge['question'] ); ?></strong></label>
		<input id="<?php echo esc_attr( $field_id ); ?>" type="text" name="ame_captcha_answer" inputmode="numeric" pattern="[0-9]*" maxlength="3" autocomplete="off" required>
	</div>
	<div class="ame-login-honeypot" aria-hidden="true">
		<label for="<?php echo esc_attr( $field_id . '-website' ); ?>"><?php esc_html_e( 'Website', 'andalan-mutu-energi' ); ?></label>
		<input id="<?php echo esc_attr( $field_id . '-website' ); ?>" type="text" name="ame_login_website" tabindex="-1" autocomplete="off">
	</div>
	<?php
	return ob_get_clean();
}

/**
 * Add CAPTCHA to the native WordPress login form.
 *
 * @return void
 */
function ame_login_wp_form_captcha() {
	echo ame_login_captcha_fields(); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Internally escaped form markup.
}
add_action( 'login_form', 'ame_login_wp_form_captcha' );

/**
 * Whether the current request is a native web credential login submission.
 *
 * XML-RPC and application-password flows are left to the brute-force firewall.
 *
 * @return bool
 */
function ame_login_is_wp_login_submission() {
	global $pagenow;
	$method = isset( $_SERVER['REQUEST_METHOD'] ) && is_string( $_SERVER['REQUEST_METHOD'] ) ? strtoupper( sanitize_text_field( wp_unslash( $_SERVER['REQUEST_METHOD'] ) ) ) : '';
	return 'wp-login.php' === $pagenow && 'POST' === $method && isset( $_POST['log'], $_POST['pwd'] );
}

/**
 * Validate CAPTCHA after WordPress authentication, before the firewall result.
 *
 * Returning the CAPTCHA error at this late priority also prevents valid
 * credentials from succeeding when the challenge is absent, expired, or wrong.
 *
 * @param WP_User|WP_Error|null $user     Authentication result.
 * @param string                $username Submitted username, unused.
 * @param string                $password Submitted password, unused.
 * @return WP_User|WP_Error|null
 */
function ame_login_captcha_authenticate( $user, $username, $password ) {
	if ( ! get_theme_mod( 'ame_login_captcha_enabled', true ) || ! ame_login_is_wp_login_submission() ) {
		return $user;
	}
	if ( ! ame_login_captcha_validate_request() ) {
		return new WP_Error( 'ame_captcha_failed', __( 'Jawaban CAPTCHA tidak valid atau sudah kedaluwarsa. Silakan coba lagi.', 'andalan-mutu-energi' ) );
	}
	return $user;
}
add_filter( 'authenticate', 'ame_login_captcha_authenticate', 90, 3 );

